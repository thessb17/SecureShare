"""Encrypted object storage abstraction.

Only ciphertext ever reaches a backend. Object identifiers are generated by the
server from a CSPRNG - the client never influences a filesystem path, so path
traversal is structurally impossible (and still re-validated defensively).

The local backend writes to a directory that is *outside* any web root and is
never routed by nginx; see ``nginx/nginx.conf``.
"""
from __future__ import annotations

import logging
import os
import re
import secrets
import stat
from abc import ABC, abstractmethod
from contextlib import contextmanager
from pathlib import Path
from typing import BinaryIO, Final, Iterator

from django.conf import settings
from django.utils.module_loading import import_string

from security.exceptions import ObjectNotFound, StorageError

logger = logging.getLogger("secureshare.security")

#: 43 chars of base64url == 256 bits of entropy (``secrets.token_urlsafe(32)``).
OBJECT_ID_RE: Final[re.Pattern[str]] = re.compile(r"^[A-Za-z0-9_-]{32,64}$")
OBJECT_ID_BYTES: Final[int] = 32


def generate_object_id() -> str:
    """Unpredictable storage object identifier (never derived from user data)."""
    return secrets.token_urlsafe(OBJECT_ID_BYTES)


def validate_object_id(object_id: str) -> str:
    if not isinstance(object_id, str) or not OBJECT_ID_RE.match(object_id):
        raise StorageError("Invalid storage object identifier.")
    return object_id


class EncryptedObjectStorage(ABC):
    """Interface implemented by every storage backend."""

    @abstractmethod
    def write(self, object_id: str) -> "AbstractContextManager[BinaryIO]":  # noqa: F821
        """Context manager yielding a writable stream, committed atomically."""

    @abstractmethod
    def open(self, object_id: str) -> BinaryIO:
        """Open an object for reading."""

    @abstractmethod
    def delete(self, object_id: str) -> bool:
        """Delete an object; returns True when something was removed."""

    @abstractmethod
    def exists(self, object_id: str) -> bool: ...

    @abstractmethod
    def size(self, object_id: str) -> int: ...

    @abstractmethod
    def health_check(self) -> bool: ...

    @staticmethod
    def allocate_object_id() -> str:
        return generate_object_id()


class LocalEncryptedStorage(EncryptedObjectStorage):
    """Filesystem backend used for development and the test-suite.

    Objects are sharded two levels deep to keep directories small::

        storage/encrypted/<xx>/<yy>/<object-id>
    """

    def __init__(self, root: Path | str | None = None) -> None:
        self.root = Path(root or settings.ENCRYPTED_STORAGE_ROOT).resolve()
        self.tmp_dir = self.root / "_incoming"
        self.root.mkdir(parents=True, exist_ok=True)
        self.tmp_dir.mkdir(parents=True, exist_ok=True)
        try:
            os.chmod(self.root, 0o700)
            os.chmod(self.tmp_dir, 0o700)
        except OSError:  # pragma: no cover - best effort on exotic filesystems
            logger.warning("Could not tighten permissions on the storage root")

    # -- paths -------------------------------------------------------------
    def _path_for(self, object_id: str) -> Path:
        validate_object_id(object_id)
        shard = self.root / object_id[:2] / object_id[2:4]
        path = (shard / object_id).resolve()
        # Defence in depth: the resolved path must stay inside the root.
        if not str(path).startswith(str(self.root) + os.sep):
            raise StorageError("Resolved object path escapes the storage root.")
        return path

    def _make_shard(self, shard: Path) -> None:
        """Create the shard directories with 0700, independent of the umask.

        ``mkdir(mode=...)`` is masked by the process umask (typically 022),
        which would leave the shard world-readable. The root is already 0700 so
        this is defence in depth, but the ciphertext tree should never widen
        just because the service inherited a permissive umask.
        """
        shard.mkdir(parents=True, exist_ok=True)
        for directory in (shard, shard.parent):
            if directory == self.root:
                break
            try:
                if stat.S_IMODE(directory.stat().st_mode) != 0o700:
                    os.chmod(directory, 0o700)
            except OSError:  # pragma: no cover - best effort
                logger.warning("Could not tighten permissions on a storage shard")

    # -- API ---------------------------------------------------------------
    @contextmanager
    def write(self, object_id: str) -> Iterator[BinaryIO]:
        """Write to a temp file, fsync, then atomically ``os.replace`` it.

        A crash or exception mid-upload leaves no readable object behind.
        """
        final_path = self._path_for(object_id)
        self._make_shard(final_path.parent)
        tmp_path = self.tmp_dir / f"{object_id}.{secrets.token_hex(8)}.part"

        handle = os.open(tmp_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        stream = os.fdopen(handle, "wb")
        try:
            yield stream
            stream.flush()
            os.fsync(stream.fileno())
        except Exception:
            stream.close()
            tmp_path.unlink(missing_ok=True)
            raise
        else:
            stream.close()
            os.replace(tmp_path, final_path)
            os.chmod(final_path, 0o600)
        finally:
            if not stream.closed:  # pragma: no cover - defensive
                stream.close()
            tmp_path.unlink(missing_ok=True)

    def open(self, object_id: str) -> BinaryIO:
        path = self._path_for(object_id)
        try:
            return open(path, "rb")
        except FileNotFoundError as exc:
            raise ObjectNotFound("Encrypted object is missing from storage.") from exc
        except OSError as exc:
            raise StorageError("Encrypted object could not be opened.") from exc

    def delete(self, object_id: str) -> bool:
        path = self._path_for(object_id)
        try:
            path.unlink()
        except FileNotFoundError:
            return False
        except OSError as exc:
            raise StorageError("Encrypted object could not be deleted.") from exc
        for parent in (path.parent, path.parent.parent):
            try:
                parent.rmdir()
            except OSError:
                break
        return True

    def exists(self, object_id: str) -> bool:
        try:
            return self._path_for(object_id).is_file()
        except StorageError:
            return False

    def size(self, object_id: str) -> int:
        path = self._path_for(object_id)
        try:
            return path.stat().st_size
        except FileNotFoundError as exc:
            raise ObjectNotFound("Encrypted object is missing from storage.") from exc

    def health_check(self) -> bool:
        probe = self.tmp_dir / f"healthcheck.{secrets.token_hex(6)}"
        try:
            probe.write_bytes(b"ok")
            data = probe.read_bytes()
            return data == b"ok"
        except OSError:
            return False
        finally:
            probe.unlink(missing_ok=True)

    def usage_bytes(self) -> int:
        """Total ciphertext stored (used by the admin statistics endpoint)."""
        total = 0
        for path in self.root.rglob("*"):
            if path.is_file():
                total += path.stat().st_size
        return total


class S3EncryptedStorage(EncryptedObjectStorage):
    """S3-compatible backend (MinIO/AWS).

    Enabled with ``ENCRYPTED_STORAGE_BACKEND=security.storage.S3EncryptedStorage``
    plus ``S3_BUCKET``/``S3_ENDPOINT_URL`` and standard AWS credentials in the
    environment. Objects are already client-side encrypted by SecureShare; S3
    server-side encryption is an additional, independent layer.
    """

    def __init__(self) -> None:
        try:
            import boto3
        except ImportError as exc:  # pragma: no cover - optional dependency
            raise StorageError(
                "boto3 is required for the S3 storage backend "
                "(pip install boto3)."
            ) from exc
        self.bucket = getattr(settings, "S3_BUCKET", "") or ""
        if not self.bucket:
            raise StorageError("S3_BUCKET must be configured for S3 storage.")
        self.prefix = getattr(settings, "S3_PREFIX", "encrypted/")
        self.client = boto3.client(
            "s3",
            endpoint_url=getattr(settings, "S3_ENDPOINT_URL", None) or None,
            region_name=getattr(settings, "S3_REGION", None) or None,
        )

    def _key(self, object_id: str) -> str:
        validate_object_id(object_id)
        return f"{self.prefix}{object_id}"

    @contextmanager
    def write(self, object_id: str) -> Iterator[BinaryIO]:  # pragma: no cover
        import tempfile

        with tempfile.TemporaryFile() as buffer:
            yield buffer  # type: ignore[misc]
            buffer.seek(0)
            self.client.upload_fileobj(buffer, self.bucket, self._key(object_id))

    def open(self, object_id: str) -> BinaryIO:  # pragma: no cover
        import tempfile

        buffer = tempfile.TemporaryFile()  # noqa: SIM115 - closed on every path below
        try:
            self.client.download_fileobj(self.bucket, self._key(object_id), buffer)
        except Exception as exc:
            buffer.close()
            raise ObjectNotFound("Encrypted object is missing from storage.") from exc
        buffer.seek(0)
        return buffer  # type: ignore[return-value]

    def delete(self, object_id: str) -> bool:  # pragma: no cover
        self.client.delete_object(Bucket=self.bucket, Key=self._key(object_id))
        return True

    def exists(self, object_id: str) -> bool:  # pragma: no cover
        try:
            self.client.head_object(Bucket=self.bucket, Key=self._key(object_id))
        except Exception:
            return False
        return True

    def size(self, object_id: str) -> int:  # pragma: no cover
        meta = self.client.head_object(Bucket=self.bucket, Key=self._key(object_id))
        return int(meta["ContentLength"])

    def health_check(self) -> bool:  # pragma: no cover
        try:
            self.client.head_bucket(Bucket=self.bucket)
        except Exception:
            return False
        return True


_STORAGE_CACHE: dict[str, EncryptedObjectStorage] = {}


def get_storage() -> EncryptedObjectStorage:
    """Instantiate the configured storage backend (cached per configuration)."""
    dotted = settings.ENCRYPTED_STORAGE_BACKEND
    cache_key = f"{dotted}:{getattr(settings, 'ENCRYPTED_STORAGE_ROOT', '')}"
    storage = _STORAGE_CACHE.get(cache_key)
    if storage is None:
        storage = import_string(dotted)()
        _STORAGE_CACHE[cache_key] = storage
    return storage


def reset_storage_cache() -> None:
    _STORAGE_CACHE.clear()
